#!/usr/bin/env node
/**
 * Splits a changelog-data.js master file into paginated files (written next to the master):
 *   changelog-meta.js      - pagination meta + labels
 *   changelog-page-{n}.js  - pageSize versions per file
 *
 * Usage: node tools/split-changelog.js <path-to-changelog-data.js> [pageSize]
 * Example: node tools/split-changelog.js zh-cn/apps/ling/changelog-data.js 5
 */
const fs = require('fs');
const path = require('path');

const masterPath = process.argv[2];
const pageSize = parseInt(process.argv[3], 10) || 5;

if (!masterPath) {
  console.error('Usage: node tools/split-changelog.js <path-to-changelog-data.js> [pageSize]');
  process.exit(1);
}

const absMaster = path.resolve(masterPath);
const code = fs.readFileSync(absMaster, 'utf8');
const win = {};
new Function('window', code)(win);

const data = win.CHANGELOG_DATA;
if (!Array.isArray(data) || !data.length) {
  console.error('No CHANGELOG_DATA found in ' + masterPath);
  process.exit(1);
}

const dir = path.dirname(absMaster);
const totalPages = Math.ceil(data.length / pageSize);
const header = '// Auto-generated by tools/split-changelog.js - do not edit. Edit changelog-data.js and re-run the script.\n';

const meta = {
  totalVersions: data.length,
  pageSize: pageSize,
  totalPages: totalPages
};
fs.writeFileSync(
  path.join(dir, 'changelog-meta.js'),
  header +
    'window.CHANGELOG_META = ' + JSON.stringify(meta, null, 2) + ';\n\n' +
    'window.TYPE_LABELS = ' + JSON.stringify(win.TYPE_LABELS || {}, null, 2) + ';\n\n' +
    'window.CHANGELOG_LABELS = ' + JSON.stringify(win.CHANGELOG_LABELS || {}, null, 2) + ';\n'
);

for (let p = 1; p <= totalPages; p++) {
  const entries = data.slice((p - 1) * pageSize, p * pageSize);
  fs.writeFileSync(
    path.join(dir, 'changelog-page-' + p + '.js'),
    header +
      'window.CHANGELOG_PAGES = window.CHANGELOG_PAGES || {};\n' +
      'window.CHANGELOG_PAGES[' + p + '] = ' + JSON.stringify(entries, null, 2) + ';\n'
  );
}

// Remove stale page files beyond totalPages
let stale = totalPages + 1;
while (fs.existsSync(path.join(dir, 'changelog-page-' + stale + '.js'))) {
  fs.unlinkSync(path.join(dir, 'changelog-page-' + stale + '.js'));
  stale++;
}

console.log('OK: ' + masterPath + ' -> ' + data.length + ' versions, ' + totalPages + ' pages (pageSize=' + pageSize + ')');
